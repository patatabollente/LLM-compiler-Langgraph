from typing import Annotated, Any

from pydantic import BaseModel, ConfigDict, Field

NonEmptyStr = Annotated[str, Field(min_length=1)]

_BASE_CONFIG = ConfigDict(
    extra="forbid",
    frozen=True,
    str_strip_whitespace=True,
)


class InputBinding(BaseModel):
    """Reference to an output value produced by an upstream task."""

    model_config = _BASE_CONFIG

    task_id: NonEmptyStr = Field(
        description="Identifier of the upstream task producing the value."
    )

    output_path: list[NonEmptyStr] = Field(
        default_factory=list,
        description=(
            "Sequence of keys to traverse in the upstream task output. "
            "Empty list refers to the entire output."
        ),
    )


TaskInputValue = Annotated[
    InputBinding | Any,
    Field(union_mode="left_to_right"),
]


class TaskSpec(BaseModel):
    """Single atomic task in an ExecutionPlan.

    Each parameter in `inputs` holds either a static value or an `InputBinding`
    referencing an upstream task's output. Unifying static and dynamic parameters
    in a single mapping makes argument/binding key collisions impossible by
    construction.
    """

    model_config = _BASE_CONFIG

    task_id: NonEmptyStr
    tool_name: NonEmptyStr
    description: NonEmptyStr
    inputs: dict[str, TaskInputValue] = Field(
        default_factory=dict,
        description=(
            "Tool input parameters. Each value is either a known static value "
            "or an InputBinding referencing an upstream task output."
        ),
    )

    @property
    def static_inputs(self) -> dict[str, Any]:
        """Return only the statically provided input parameters."""
        return {
            key: value
            for key, value in self.inputs.items()
            if not isinstance(value, InputBinding)
        }

    @property
    def bindings(self) -> dict[str, InputBinding]:
        """Return only the dynamic InputBinding parameters."""
        return {
            key: value
            for key, value in self.inputs.items()
            if isinstance(value, InputBinding)
        }


class ExecutionPlan(BaseModel):
    """Complete execution plan generated by the Planner."""

    model_config = _BASE_CONFIG

    objective: NonEmptyStr
    tasks: list[TaskSpec] = Field(
        default_factory=list,
        description=(
            "Ordered list of tasks to execute. Leave empty ([]) when no available "
            "tool is needed or applicable (e.g., greetings, conversational messages, "
            "or requests outside the tool catalog)."
        ),
    )
