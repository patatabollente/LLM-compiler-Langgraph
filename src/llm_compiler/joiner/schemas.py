from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

from llm_compiler.executor.results import ExecutionResult
from llm_compiler.planner.schemas import ExecutionPlan, NonEmptyStr

JoinerStatus = Literal["complete", "partial", "failed"]
JoinerAction = Literal["finish", "replan"]

_BASE_CONFIG = ConfigDict(
    extra="forbid",
    frozen=True,
    str_strip_whitespace=True,
)


class ExecutionRound(BaseModel):
    """Snapshot of a single completed execution round preserved across replans."""

    model_config = _BASE_CONFIG

    round_index: int = Field(ge=1)
    plan: ExecutionPlan | None = None
    execution_result: ExecutionResult
    replan_reason: NonEmptyStr | None = None


class JoinerOutput(BaseModel):
    """Structured output generated directly by the LLM when replanning is disabled."""

    model_config = _BASE_CONFIG

    answer: NonEmptyStr = Field(
        description="Final user-facing answer written in the user's original language."
    )


class JoinerDecisionOutput(BaseModel):
    """Structured output generated by the LLM when runtime replanning is allowed."""

    model_config = _BASE_CONFIG

    action: JoinerAction = Field(
        description=(
            "'finish' to deliver the final answer now, or 'replan' to request a "
            "targeted follow-up execution plan."
        )
    )
    answer: NonEmptyStr | None = Field(
        default=None,
        description=(
            "Final user-facing answer written in the user's original language. "
            "Required when action is 'finish'; set to null when action is 'replan'."
        ),
    )
    replan_reason: NonEmptyStr | None = Field(
        default=None,
        description=(
            "Concise, actionable instruction explaining what the Planner should "
            "do in the next round. Required when action is 'replan'; set to null "
            "when action is 'finish'."
        ),
    )

    @field_validator("answer", "replan_reason", mode="before")
    @classmethod
    def _normalize_empty_to_none(cls, value: Any) -> Any:
        if isinstance(value, str) and not value.strip():
            return None
        return value

    @model_validator(mode="after")
    def _validate_action_fields(self) -> "JoinerDecisionOutput":
        if self.action == "finish" and self.answer is None:
            raise ValueError("Field 'answer' is required when action is 'finish'.")
        if self.action == "replan" and self.replan_reason is None:
            raise ValueError("Field 'replan_reason' is required when action is 'replan'.")
        return self


class JoinerResult(BaseModel):
    """Application-level result returned by the Joiner component."""

    model_config = _BASE_CONFIG

    action: JoinerAction = "finish"
    answer: NonEmptyStr | None = None
    replan_reason: NonEmptyStr | None = None
    status: JoinerStatus
    missing_information: list[NonEmptyStr] = Field(default_factory=list)

    @model_validator(mode="after")
    def _validate_action_fields(self) -> "JoinerResult":
        if self.action == "finish" and self.answer is None:
            raise ValueError("Field 'answer' is required when action is 'finish'.")
        if self.action == "replan" and self.replan_reason is None:
            raise ValueError("Field 'replan_reason' is required when action is 'replan'.")
        return self
